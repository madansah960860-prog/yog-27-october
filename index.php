          <h2>How the recipes are written</h2>
          <p>Every recipe on this site follows the same shape, because once you know
            where to look for a thing you stop having to hunt for it. The total time at
            the top includes every rest and every chill, so a pie that says three hours
            genuinely means three hours from flour to first slice rather than three hours
            of your attention plus an unmentioned cooling period. Underneath that sit
            the prep time, the cook time and the number of servings.</p>
          <p>Ingredients come with their quantities in a column down one side so you can
            read them at arm's length from across the counter. Where a weight matters
            more than a volume &mdash; which in baking is nearly always &mdash; the
            weight is given first in ounces with the cup measure after it in brackets.
            Flour is always weighed, because a cup of it can vary by almost two ounces
            depending on how it got into the cup, and that variation is the whole
            difference between a tender pastry and a tough one.</p>
          <p>The method is numbered, and each step describes what you are looking for
            rather than only how long to wait. "Cook until the edges pull away from the
            pan" survives a difference in ovens; "cook for twelve minutes" does not.
            Every recipe then ends with the same four sections: storage and reheating
            with real times, how far ahead you can make it, substitutions that work and
            the ones that do not, and a short troubleshooting list for the things that
            actually go wrong.</p>
          <p>Each recipe also carries a box headed <em>Make it easier</em>. Those are not
            filler. They are the shortcuts and the small mechanical tricks that came out
            of testing &mdash; microwaving a squash for two minutes so the knife is safe,
            freezing crumble topping raw by the bagful, chilling pastry strips before you
            try to weave them. They are the difference between a recipe that works and a
            recipe that is pleasant to cook.</p>

          <h2>Who writes this</h2>
          <p>Thistledown Kitchen is a small independent publisher based in Lancaster
            County, Pennsylvania. We are not a restaurant, a farm or a grocery supplier.
            We write recipes, we test them, and we sell two things: printable recipe
            cards and a digital cookbook.</p>
          <p>Every recipe published here has been made at least three times — once to
            work out what it is, once to write it down, and once from the written version
            by someone who was not in the room the first two times. That last pass is
            where most of the corrections come from, because it catches the steps we
            assumed everyone knew. There is more about how that works on the
            <a href="about.html">About page</a>.</p>


          <h2>What this kitchen is</h2>
          <p>There is a particular kind of cooking that starts with what is in front of
            you rather than with a shopping list. You come home with more apples than you
            planned for, or someone leaves a bag of squash on the step, and the question
            becomes what to do about it before Thursday. That is the kind of cooking this
            site is for.</p>
          <p>Thistledown Kitchen is organized by the growing year rather than by course.
            The recipes are grouped into four seasons, and within each season they run
            roughly in the order the ingredients turn up. In Pennsylvania that means
            rhubarb and the first herbs in April, berries through July, apples and squash
            from late August until the hard frost, and then a long stretch of roots,
            cabbage and whatever was put away in the fall.</p>
          <p>Nothing here is complicated for the sake of it. Most of these recipes use
            one pan, a bowl and a wooden spoon. A few of them take all afternoon, and
            when they do, the recipe says so at the top so you can decide before you
            start rather than halfway through.</p>


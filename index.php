          <h2>What is good this week</h2>
          <p>Late October in southeastern Pennsylvania is the top of the apple season and
            the start of the squash one. The last of the field tomatoes are in, and they
            are better cooked than raw by now. Herbs are still going outside if the frost
            has held off, but they will not be for long, so this is the week to cut what
            you want and dry it.</p>
          <p>If you buy one thing at a stand this week, make it apples by the half bushel
            rather than by the pound. They keep for weeks somewhere cold, they bake, they
            sauce, and a bowl of them on the counter is the cheapest thing you can do for
            a kitchen.</p>

